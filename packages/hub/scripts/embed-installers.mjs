#!/usr/bin/env node
/**
 * Embeds the installer sources (packages/hub/assets/install.sh, …) as strings in
 * src/install/embedded.ts, so the root @uncage/hub entry serves them without `fs` (Web-standard
 * only). `--check` exits 1 when embedded.ts is stale instead of writing it.
 *
 *   pnpm --filter @uncage/hub embed:installers
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const pkgDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(pkgDir, 'src/install/embedded.ts');
const ASSETS = [
  ['install.sh', 'INSTALL_SH_TEMPLATE'],
  ['install.ps1', 'INSTALL_PS1_TEMPLATE'],
];

export function renderEmbedded() {
  const lines = [
    '// Generated by scripts/embed-installers.mjs from packages/hub/assets/. Do not edit.',
    '// Run `pnpm --filter @uncage/hub embed:installers` after changing an asset.',
  ];
  for (const [file, name] of ASSETS) {
    const text = readFileSync(join(pkgDir, 'assets', file), 'utf8').replace(/\r\n/g, '\n');
    lines.push('', `export const ${name}: string = ${JSON.stringify(text)};`);
  }
  return `${lines.join('\n')}\n`;
}

const next = renderEmbedded();
if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== next) {
    console.error('embed-installers: src/install/embedded.ts is stale; run `pnpm --filter @uncage/hub embed:installers`');
    process.exit(1);
  }
  console.log('embed-installers: src/install/embedded.ts is up to date');
} else {
  writeFileSync(out, next);
  console.log('embed-installers: wrote src/install/embedded.ts');
}
